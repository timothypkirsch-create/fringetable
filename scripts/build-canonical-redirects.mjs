import fs from 'node:fs';
import path from 'node:path';
const roots=['recipes','subrecipes','guides'];
const files=[];
const walk=dir=>{for(const entry of fs.readdirSync(dir,{withFileTypes:true})){const file=path.join(dir,entry.name);if(entry.isDirectory())walk(file);else if(entry.name.endsWith('.html')&&entry.name!=='index.html')files.push(file)}};
for(const root of roots)walk(root);
const rules=files.sort().map(file=>{const source=`/${file.replace(/\.html$/,'').replaceAll(path.sep,'/')}`;return `${source} https://fringetable.com${source}.html 301`});
fs.writeFileSync('_redirects',`# Exact legacy paths only. Generated by scripts/build-canonical-redirects.mjs.\n${rules.join('\n')}\n`);
console.log(`Built ${rules.length} canonical redirect rules.`);
