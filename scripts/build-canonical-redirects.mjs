import fs from 'node:fs';
import path from 'node:path';
const roots=['recipes','subrecipes','guides'];
const files=[];
const walk=dir=>{for(const entry of fs.readdirSync(dir,{withFileTypes:true})){const file=path.join(dir,entry.name);if(entry.isDirectory())walk(file);else if(entry.name.endsWith('.html')&&entry.name!=='index.html')files.push(file)}};
for(const root of roots)walk(root);
const rules=['/ /index.html 200'];
const indexFiles=[];
const collectIndexes=dir=>{for(const entry of fs.readdirSync(dir,{withFileTypes:true})){if(entry.name==='.git')continue;const file=path.join(dir,entry.name);if(entry.isDirectory())collectIndexes(file);else if(entry.name==='index.html')indexFiles.push(file)}};
collectIndexes('.');
for(const file of indexFiles.sort()){
  const dir=path.dirname(file).replaceAll(path.sep,'/').replace(/^\.\/?/,'');
  if(!dir)continue;
  rules.push(`/${dir} /${dir}/ 301`,`/${dir}/ /${dir}/index.html 200`);
}
for(const file of fs.readdirSync('.').filter(name=>name.endsWith('.html')&&name!=='index.html').sort()){
  const source=`/${file.replace(/\.html$/,'')}`;
  rules.push(`${source} https://fringetable.com${source}.html 301`);
}
rules.push(...files.sort().map(file=>{const source=`/${file.replace(/\.html$/,'').replaceAll(path.sep,'/')}`;return `${source} https://fringetable.com${source}.html 301`}));
fs.writeFileSync('_redirects',`# Exact canonical redirects and directory-index rewrites. Generated by scripts/build-canonical-redirects.mjs.\n${rules.join('\n')}\n`);
console.log(`Built ${rules.length} canonical redirect rules.`);
